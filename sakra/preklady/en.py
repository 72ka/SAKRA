def _typ_s_kodem(m) -> str:
    """Typ PMD 85 „> BASIC“, „D Data BASICu“…: kód typu a známý název; jinak beze změny."""
    t = TEXTY.get(m.group(2))
    return f"{m.group(1)} {t}" if t else m.group(0)
